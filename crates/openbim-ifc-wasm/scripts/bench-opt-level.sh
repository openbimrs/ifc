#!/usr/bin/env bash
# Compare STEP parse time and download size of the wasm module across
# opt-levels, in Node (#303).
#
#   crates/openbim-ifc-wasm/scripts/bench-opt-level.sh [out-dir]
#
# Builds the default (npm) feature set once per opt-level -- 3, "s" and
# "z" through CARGO_PROFILE_RELEASE_OPT_LEVEL, every other release-profile
# setting unchanged -- binds each with wasm-bindgen --target nodejs, then
# runs tools/bench-parse.mjs over all of them, interleaved in one process.
#
# Inputs: three redistributable fixtures from test/fixtures (see
# PROVENANCE.tsv) and two synthetic IFC4 files of about 1 MB and 10 MB
# generated by benchmarks/generate-fixture.awk into the out-dir. Nothing
# generated is committed.
#
# Environment: RUNS (default 30) and WARMUP (default 5) per build and
# file; LEVELS (default "3 s z"), the first being the baseline the others
# are compared with. Measure on a quiet machine and report the load
# average the run prints; nothing else may build while it runs.
set -euo pipefail

crate_dir="$(cd "$(dirname "$0")/.." && pwd)"
root="$(cd "$crate_dir/../.." && pwd)"
out="${1:-$(mktemp -d "${TMPDIR:-/tmp}/openbim-ifc-wasm-bench.XXXXXX")}"
levels="${LEVELS:-3 s z}"
mkdir -p "$out"

command -v wasm-bindgen >/dev/null || {
    echo "error: wasm-bindgen CLI missing; see crates/openbim-ifc-wasm/README.md" >&2
    exit 1
}

target_dir="${CARGO_TARGET_DIR:-$root/target}"
module="$target_dir/wasm32-unknown-unknown/release/openbim_ifc_wasm.wasm"
builds=()
for level in $levels; do
    (cd "$root" && CARGO_PROFILE_RELEASE_OPT_LEVEL="$level" \
        cargo build -p openbim-ifc-wasm --target wasm32-unknown-unknown --release)
    rm -rf "$out/opt-$level"
    wasm-bindgen --target nodejs --out-dir "$out/opt-$level" "$module"
    builds+=("opt-level-$level=$out/opt-$level")
done

fixtures=(
    "$root/test/fixtures/synthetic-coverage/meshing_coverage.ifc"
    "$root/test/fixtures/ifclite-geometry/issue_098_wall_W.ifc"
    "$root/test/fixtures/ifclite-geometry/shared_point_faceted_brep.ifc"
)
# 1,800 and 18,000 walls: 18,008 and 180,008 entities (benchmarks/README.md).
for walls in 1800 18000; do
    awk -v n="$walls" -f "$root/benchmarks/generate-fixture.awk" >"$out/synthetic-$walls-walls.ifc"
    fixtures+=("$out/synthetic-$walls-walls.ifc")
done

node "$crate_dir/tools/bench-parse.mjs" \
    --runs "${RUNS:-30}" --warmup "${WARMUP:-5}" --json "$out/results.json" \
    "${builds[@]}" -- "${fixtures[@]}"
echo "results: $out/results.json"
